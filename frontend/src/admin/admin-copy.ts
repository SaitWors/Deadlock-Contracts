const english = new Map(translations)
const russian = new Map(translations.map(([ru, en]) => [en, ru]))

export function useAdminCopy() {
  const { language, locale } = useLanguage()
  const copy = useCallback(
    (source: string, values: Record<string, unknown> = {}) => {
      const key = source.trim()
      const translated =
        codeLabels[key]?.[language === "ru" ? 0 : 1] ??
        (language === "ru" ? russian : english).get(key) ??
        key
      const text = source.replace(key, translated)
      return text.replace(/\{(\d+)\}/g, (token, index: string) =>
        index in values ? String(values[index]) : token,
      )
    },
    [language],
  )
  return { copy, language, locale }
}
